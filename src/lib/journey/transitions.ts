/** Find the transition rules matching a command. */
export function rulesForCommand(command: string): readonly TransitionRule[] {
  return TRANSITIONS.filter((t) => t.command === command);
}

/** Find the transition rule for a command from a specific stage. */
export function findTransition(
  command: string,
  from: JourneyStage,
): TransitionRule | undefined {
  return TRANSITIONS.find((t) => t.command === command && t.from.includes(from));
}
